"""SystemVerilog export of quantized designs, bit-exact with simulate_fir_fixed / simulate_sos_fixed.

The generated modules take one sample per clock (in_valid / in_data), register the result (out_valid /
out_data one clock later) and reset synchronously (rst, active high). The text uses a small, regular SV subset
so that tests/rtl_eval.py can execute it independently of the Python simulator. web/rtl.js produces
byte-identical text.
"""
import re
import numpy as np
from .quant import QFormat, simulate_fir_fixed, simulate_sos_fixed

def _check(overflow, module_name):
    if overflow not in ("saturate", "wrap"):
        raise ValueError(f"overflow must be 'saturate' or 'wrap', not {overflow!r}")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]{0,63}", module_name or ""):
        raise ValueError(f"module_name must be a SystemVerilog identifier, not {module_name!r}")

def _lit(v):
    """Signed sized literal one bit wider than |v| needs, so -2^(n-1) is written without overflow."""
    v = int(v); w = max(abs(v).bit_length() + 1, 2)
    return f"-{w}'sd{-v}" if v < 0 else f"{w}'sd{v}"

def _decl(width, names):
    return f"  logic signed [{width - 1}:0] {', '.join(names)};"

def acc_width_fir(h_int, coef_fmt, sig_fmt):
    """Bits for |acc + half| <= sum|h| 2^(SW-1) + 2^(SH-1): bitlen(M) + 1 (sign)."""
    sh = coef_fmt.frac_bits; half = 1 << (sh - 1) if sh > 0 else 0
    return (sum(abs(int(v)) for v in h_int) * (1 << (sig_fmt.word - 1)) + half).bit_length() + 1

def acc_width_sos(row, coef_fmt, sig_fmt, error_feedback=False):
    """Bits for one DF-I section: (|b0|+|b1|+|b2|+|a1|+|a2|) 2^(SW-1) + (|c1|+|c2|) 2^(SH-1) + 2^(SH-1)."""
    sh = coef_fmt.frac_bits; half = 1 << (sh - 1) if sh > 0 else 0
    c = _ef_coefs(row, sh) if error_feedback else (0, 0)
    m = sum(abs(int(v)) for v in row) * (1 << (sig_fmt.word - 1)) + (abs(c[0]) + abs(c[1])) * half + half
    return m.bit_length() + 1

def _ef_coefs(row, sh):
    half = 1 << (sh - 1) if sh > 0 else 0
    return ((int(row[3]) + half) >> sh, (int(row[4]) + half) >> sh)     # round(a1), round(a2), as the simulator

def _round_and_limit(lines, p, W, sh, sig_fmt, overflow, out):
    """acc (W bits) -> rounded yr -> out (SW bits), as simulate_*_fixed: (acc + half) >> sh, then saturate or wrap."""
    SW = sig_fmt.word
    if sh > 0:
        lines += [_decl(W, [f"{p}accr", f"{p}yr"]), f"  assign {p}accr = {p}acc + {_lit(1 << (sh - 1))};",
                  f"  assign {p}yr = {p}accr >>> {sh};"]
    else:
        lines += [_decl(W, [f"{p}yr"]), f"  assign {p}yr = {p}acc;"]
    lines.append(_decl(SW, [out]))
    if overflow == "saturate":
        hi, lo = (1 << (SW - 1)) - 1, -(1 << (SW - 1))
        lines.append(f"  assign {out} = ({p}yr > {_lit(hi)}) ? {_lit(hi)} : (({p}yr < {_lit(lo)}) ? {_lit(lo)} : {p}yr);")
    else:
        lines.append(f"  assign {out} = {p}yr;   // implicit truncation = two's-complement wrap")

def _header(title, sig_fmt, coef_fmt, overflow, extra):
    SW, sh = sig_fmt.word, coef_fmt.frac_bits
    return [f"// {title}",
            "// Generated by Filterlab (dsp/rtl.py). Generated, not synthesized.",
            f"// Signal: Q{sig_fmt.int_bits}.{sig_fmt.frac_bits} ({SW} bits) in and out. Coefficients: Q{coef_fmt.int_bits}.{coef_fmt.frac_bits} integers, SH = {sh}.",
            f"// Rounding: round half up, (acc + 2^(SH-1)) >>> SH. Overflow: {overflow}.",
            *extra,
            "// Interface: one sample per clock when in_valid is high; out_data/out_valid are registered (latency 1 clock);",
            "// rst is synchronous and active high. The arithmetic matches simulate_*_fixed bit for bit."]

def _ports(name, SW):
    return [f"module {name} (", "  input  logic clk,", "  input  logic rst,", "  input  logic in_valid,",
            f"  input  logic signed [{SW - 1}:0] in_data,", "  output logic out_valid,",
            f"  output logic signed [{SW - 1}:0] out_data", ");"]

def _regs(lines, regs, updates):
    lines += ["  always_ff @(posedge clk) begin", "    if (rst) begin"]
    lines += [f"      {r} <= '0;" for r in regs] + ["      out_valid <= 1'b0;", "    end else begin",
              "      out_valid <= in_valid;", "      if (in_valid) begin"]
    lines += [f"        {r} <= {src};" for r, src in updates] + ["      end", "    end", "  end", "endmodule", ""]
    return "\n".join(lines)

def gen_fir_sv(h_int, coef_fmt, sig_fmt, *, overflow="saturate", form="direct", module_name="fir_q"):
    """FIR with an exact wide accumulator and one rounding at the output, like simulate_fir_fixed.
    form: "direct" (tap delay line) or "transposed" (registered partial sums, same exact result)."""
    _check(overflow, module_name)
    if form not in ("direct", "transposed"):
        raise ValueError(f"form must be 'direct' or 'transposed', not {form!r}")
    h = [int(v) for v in h_int]; N, SW, sh = len(h), sig_fmt.word, coef_fmt.frac_bits
    W = acc_width_fir(h, coef_fmt, sig_fmt); M = (1 << (W - 1)) - 1
    lines = _header(f"{module_name}: {form}-form FIR, {N} taps", sig_fmt, coef_fmt, overflow,
                    [f"// Accumulator: |acc + 2^(SH-1)| <= sum|h| * 2^(SW-1) + 2^(SH-1) <= 2^{W - 1} - 1, so ACC_W = {W} bits (no overflow inside)."])
    lines += _ports(module_name, SW)
    if form == "direct":
        regs = [f"x{k}" for k in range(1, N)]
        if regs: lines.append(_decl(SW, regs))
        lines.append(_decl(W, ["acc"]))
        sig = lambda k: "in_data" if k == 0 else f"x{k}"
        lines.append("  assign acc =\n" + "\n".join(f"    {'+ ' if k else '  '}({_lit(h[k])}) * {sig(k)}" for k in range(N)) + ";")
        updates = [("x1", "in_data")] * (N > 1) + [(f"x{k}", f"x{k - 1}") for k in range(2, N)]
    else:
        regs = [f"p{k}" for k in range(1, N)]
        if regs: lines += [_decl(W, regs), _decl(W, [f"pn{k}" for k in range(1, N)])]
        lines.append(_decl(W, ["acc"]))
        lines.append(f"  assign acc = ({_lit(h[0])}) * in_data" + (" + p1;" if N > 1 else ";"))
        for k in range(1, N):
            lines.append(f"  assign pn{k} = ({_lit(h[k])}) * in_data" + (f" + p{k + 1};" if k + 1 < N else ";"))
        updates = [(f"p{k}", f"pn{k}") for k in range(1, N)]
    _round_and_limit(lines, "", W, sh, sig_fmt, overflow, "y")
    return _regs(lines, regs + ["out_data"], updates + [("out_data", "y")])

def gen_sos_sv(sos_int, coef_fmt, sig_fmt, *, overflow="saturate", headroom_bits=0, error_feedback=False, module_name="sos_q"):
    """Cascade of direct-form-I biquads, one rounding per section, like simulate_sos_fixed.
    sos_int rows are integer [b0, b1, b2, a1, a2] (a0 = 1 implied), i.e. to_int(sos[:, [0, 1, 2, 4, 5]], coef_fmt)
    of the peak-scaled, quantized cascade from quantize_sos. The module outputs the cascade output; multiply it by
    quantize_sos's leftover gain times 2^headroom_bits downstream, exactly as for the simulator."""
    _check(overflow, module_name)
    rows = [[int(v) for v in r] for r in sos_int]; SW, sh, h = sig_fmt.word, coef_fmt.frac_bits, int(headroom_bits)
    RW = max(sh + 1, 2)
    widths = [acc_width_sos(r, coef_fmt, sig_fmt, error_feedback) for r in rows]
    extra = [f"// Sections: {len(rows)} direct-form-I biquads. Section k accumulator: |acc + 2^(SH-1)| <= (|b0|+|b1|+|b2|+|a1|+|a2|) * 2^(SW-1)",
             f"//   + (|c1|+|c2|) * 2^(SH-1) + 2^(SH-1), so ACC_W per section = {', '.join(map(str, widths))} bits.",
             f"// Input headroom: {h} bit(s), applied as (in_data + 2^(h-1)) >>> h. The leftover gain is not in this module:",
             f"// multiply out_data by quantize_sos's gain times 2^{h} downstream."]
    if error_feedback:
        extra.append(f"// Error feedback: acc' = acc - c1*r[n-1] - c2*r[n-2], c = round(a); r = acc' - (yr <<< SH) is {RW} bits.")
    lines = _header(f"{module_name}: biquad cascade", sig_fmt, coef_fmt, overflow, extra) + _ports(module_name, SW)
    if h > 0:
        lines += [_decl(SW + 1, ["xh"]), _decl(SW, ["xs"]), f"  assign xh = in_data + {_lit(1 << (h - 1))};", f"  assign xs = xh >>> {h};"]
        v = "xs"
    else:
        v = "in_data"
    regs, updates = [], []
    for i, (r, W) in enumerate(zip(rows, widths)):
        p = f"s{i}_"; b0, b1, b2, a1, a2 = r
        st = [f"{p}x1", f"{p}x2", f"{p}y1", f"{p}y2"]
        lines += [f"  // section {i}: b = {b0} {b1} {b2}, a = 1 {a1} {a2}", _decl(SW, st)]
        terms = f"({_lit(b0)}) * {v} + ({_lit(b1)}) * {p}x1 + ({_lit(b2)}) * {p}x2 - ({_lit(a1)}) * {p}y1 - ({_lit(a2)}) * {p}y2"
        if error_feedback:
            c1, c2 = _ef_coefs(r, sh)
            lines.append(_decl(RW, [f"{p}r1", f"{p}r2", f"{p}r"]))
            terms += f"\n    - ({_lit(c1)}) * {p}r1 - ({_lit(c2)}) * {p}r2"
            st += [f"{p}r1", f"{p}r2"]
        lines += [_decl(W, [f"{p}acc"]), f"  assign {p}acc = {terms};"]
        _round_and_limit(lines, p, W, sh, sig_fmt, overflow, f"{p}y")
        updates += [(f"{p}x1", v), (f"{p}x2", f"{p}x1"), (f"{p}y1", f"{p}y"), (f"{p}y2", f"{p}y1")]
        if error_feedback:
            lines.append(f"  assign {p}r = {p}acc - ({p}yr <<< {sh});")
            updates += [(f"{p}r1", f"{p}r"), (f"{p}r2", f"{p}r1")]
        regs += st; v = f"{p}y"
    return _regs(lines, regs + ["out_data"], updates + [("out_data", v)])

# ---------- vectors and testbench ----------
def rtl_stimulus(sig_fmt, seed=1):
    """Integer input samples: impulse (64), full-scale step (64), full-scale square (128, period 32), seeded random (256)."""
    hi, lo = (1 << (sig_fmt.word - 1)) - 1, -(1 << (sig_fmt.word - 1))
    imp = np.zeros(64, np.int64); imp[0] = hi
    step = np.full(64, hi, np.int64)
    sq = np.where((np.arange(128) // 16) % 2 == 0, hi, lo).astype(np.int64)
    rnd = np.random.default_rng(seed).integers(lo, hi + 1, 256)
    return np.concatenate([imp, step, sq, rnd])

def rtl_expected_fir(h_int, coef_fmt, sig_fmt, x_int, *, overflow="saturate"):
    y = simulate_fir_fixed(np.asarray(h_int) * coef_fmt.lsb, np.asarray(x_int) * sig_fmt.lsb, coef_fmt, sig_fmt, overflow=overflow)[0]
    return np.round(y / sig_fmt.lsb).astype(np.int64)

def rtl_expected_sos(sos_int, coef_fmt, sig_fmt, x_int, *, overflow="saturate", headroom_bits=0, error_feedback=False):
    s = np.asarray(sos_int, float) * coef_fmt.lsb
    sos = np.column_stack([s[:, :3], np.ones(len(s)), s[:, 3:]])
    y = simulate_sos_fixed(sos, np.asarray(x_int) * sig_fmt.lsb, coef_fmt, sig_fmt, overflow=overflow,
                           headroom_bits=headroom_bits, error_feedback=error_feedback)
    return np.round(y / sig_fmt.lsb).astype(np.int64)

def vectors_hex(x_int, y_int, sig_fmt):
    """One line per sample for $readmemh: {in_data, expected out_data}, two's complement, 2*SW bits in hex."""
    SW = sig_fmt.word; mask = (1 << SW) - 1; digits = (2 * SW + 3) // 4
    return "".join(f"{((int(x) & mask) << SW) | (int(y) & mask):0{digits}x}\n" for x, y in zip(x_int, y_int))

def gen_testbench_sv(module_name, sig_fmt, n_vectors, vectors_file):
    """Self-checking testbench: reset, then one vector per clock; prints PASS or FAIL with the mismatch count."""
    SW = sig_fmt.word
    return "\n".join([
        "`timescale 1ns/1ps",
        f"// Testbench for {module_name}, generated by Filterlab. Expected outputs come from simulate_*_fixed.",
        f"module {module_name}_tb;",
        "  logic clk = 1'b0, rst = 1'b1, in_valid = 1'b0, out_valid;",
        f"  logic signed [{SW - 1}:0] in_data = '0, out_data;",
        f"  logic [{2 * SW - 1}:0] vec [0:{n_vectors - 1}];",
        "  integer i, errors = 0;",
        f"  {module_name} dut (.clk(clk), .rst(rst), .in_valid(in_valid), .in_data(in_data), .out_valid(out_valid), .out_data(out_data));",
        "  always #5 clk = ~clk;",
        "  initial begin",
        f'    $readmemh("{vectors_file}", vec);',
        "    repeat (2) @(posedge clk);",
        "    @(negedge clk) rst = 1'b0;",
        f"    for (i = 0; i < {n_vectors}; i = i + 1) begin",
        f"      @(negedge clk) begin in_valid = 1'b1; in_data = vec[i][{2 * SW - 1}:{SW}]; end",
        "      @(posedge clk) #1;",
        f"      if (!out_valid || out_data !== $signed(vec[i][{SW - 1}:0])) begin",
        "        errors = errors + 1;",
        f'        if (errors <= 10) $display("mismatch at %0d: in %0d, got %0d, expected %0d", i, in_data, out_data, $signed(vec[i][{SW - 1}:0]));',
        "      end",
        "    end",
        f'    $display("{module_name}: %0d vectors, %0d mismatches", {n_vectors}, errors);',
        '    if (errors == 0) $display("PASS"); else $display("FAIL");',
        "    $finish;",
        "  end",
        "endmodule", ""])
