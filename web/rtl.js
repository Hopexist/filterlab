/* SystemVerilog export: line-for-line port of dsp/rtl.py; tests/cross_check.js requires byte-identical text. */
(function (root) {
'use strict';
const bitlen = v => (v === 0 || v === 0n) ? 0 : (v < 0 ? -v : v).toString(2).length;   // exact, also for BigInt
const ID = /^[A-Za-z_][A-Za-z0-9_]{0,63}$/;

function check(overflow, moduleName) {
  if (overflow !== 'saturate' && overflow !== 'wrap') throw new Error(`overflow must be 'saturate' or 'wrap', not '${overflow}'`);
  if (!ID.test(moduleName || '')) throw new Error(`module name must be a SystemVerilog identifier (letters, digits, _), not '${moduleName}'`);
}
function lit(v) { const w = Math.max(bitlen(v) + 1, 2); return v < 0 ? `-${w}'sd${-v}` : `${w}'sd${v}`; }
const decl = (width, names) => `  logic signed [${width - 1}:0] ${names.join(', ')};`;
const half0 = sh => sh > 0 ? 2n ** BigInt(sh - 1) : 0n;

function accWidthFir(hInt, coefFmt, sigFmt) {
  const m = hInt.reduce((s, v) => s + BigInt(Math.abs(v)), 0n) * 2n ** BigInt(sigFmt.word - 1) + half0(coefFmt.fracBits);
  return bitlen(m) + 1;
}
function efCoefs(row, sh) { const half = sh > 0 ? Math.pow(2, sh - 1) : 0, d = Math.pow(2, sh); return [Math.floor((row[3] + half) / d), Math.floor((row[4] + half) / d)]; }
function accWidthSos(row, coefFmt, sigFmt, errorFeedback = false) {
  const sh = coefFmt.fracBits, half = half0(sh), c = errorFeedback ? efCoefs(row, sh) : [0, 0];
  const m = row.reduce((s, v) => s + BigInt(Math.abs(v)), 0n) * 2n ** BigInt(sigFmt.word - 1) + BigInt(Math.abs(c[0]) + Math.abs(c[1])) * half + half;
  return bitlen(m) + 1;
}
function roundAndLimit(lines, p, W, sh, sigFmt, overflow, out) {
  const SW = sigFmt.word;
  if (sh > 0) lines.push(decl(W, [`${p}accr`, `${p}yr`]), `  assign ${p}accr = ${p}acc + ${lit(Math.pow(2, sh - 1))};`, `  assign ${p}yr = ${p}accr >>> ${sh};`);
  else lines.push(decl(W, [`${p}yr`]), `  assign ${p}yr = ${p}acc;`);
  lines.push(decl(SW, [out]));
  if (overflow === 'saturate') {
    const hi = Math.pow(2, SW - 1) - 1, lo = -Math.pow(2, SW - 1);
    lines.push(`  assign ${out} = (${p}yr > ${lit(hi)}) ? ${lit(hi)} : ((${p}yr < ${lit(lo)}) ? ${lit(lo)} : ${p}yr);`);
  } else lines.push(`  assign ${out} = ${p}yr;   // implicit truncation = two's-complement wrap`);
}
function header(title, sigFmt, coefFmt, overflow, extra) {
  const SW = sigFmt.word, sh = coefFmt.fracBits;
  return [`// ${title}`,
    '// Generated by Filterlab (dsp/rtl.py). Generated, not synthesized.',
    `// Signal: Q${sigFmt.intBits}.${sigFmt.fracBits} (${SW} bits) in and out. Coefficients: Q${coefFmt.intBits}.${coefFmt.fracBits} integers, SH = ${sh}.`,
    `// Rounding: round half up, (acc + 2^(SH-1)) >>> SH. Overflow: ${overflow}.`,
    ...extra,
    '// Interface: one sample per clock when in_valid is high; out_data/out_valid are registered (latency 1 clock);',
    '// rst is synchronous and active high. The arithmetic matches simulate_*_fixed bit for bit.'];
}
const ports = (name, SW) => [`module ${name} (`, '  input  logic clk,', '  input  logic rst,', '  input  logic in_valid,',
  `  input  logic signed [${SW - 1}:0] in_data,`, '  output logic out_valid,', `  output logic signed [${SW - 1}:0] out_data`, ');'];
function regsBlock(lines, regs, updates) {
  lines.push('  always_ff @(posedge clk) begin', '    if (rst) begin', ...regs.map(r => `      ${r} <= '0;`), "      out_valid <= 1'b0;", '    end else begin',
    '      out_valid <= in_valid;', '      if (in_valid) begin', ...updates.map(([r, s]) => `        ${r} <= ${s};`), '      end', '    end', '  end', 'endmodule', '');
  return lines.join('\n');
}

function genFirSv(hInt, coefFmt, sigFmt, { overflow = 'saturate', form = 'direct', moduleName = 'fir_q' } = {}) {
  check(overflow, moduleName);
  if (form !== 'direct' && form !== 'transposed') throw new Error(`form must be 'direct' or 'transposed', not '${form}'`);
  const h = Array.from(hInt, Number), N = h.length, SW = sigFmt.word, sh = coefFmt.fracBits, W = accWidthFir(h, coefFmt, sigFmt);
  const lines = header(`${moduleName}: ${form}-form FIR, ${N} taps`, sigFmt, coefFmt, overflow,
    [`// Accumulator: |acc + 2^(SH-1)| <= sum|h| * 2^(SW-1) + 2^(SH-1) <= 2^${W - 1} - 1, so ACC_W = ${W} bits (no overflow inside).`]);
  lines.push(...ports(moduleName, SW));
  let regs, updates;
  if (form === 'direct') {
    regs = Array.from({ length: N - 1 }, (_, i) => `x${i + 1}`);
    if (regs.length) lines.push(decl(SW, regs));
    lines.push(decl(W, ['acc']));
    const sig = k => k === 0 ? 'in_data' : `x${k}`;
    lines.push('  assign acc =\n' + h.map((v, k) => `    ${k ? '+ ' : '  '}(${lit(v)}) * ${sig(k)}`).join('\n') + ';');
    updates = (N > 1 ? [['x1', 'in_data']] : []).concat(Array.from({ length: Math.max(N - 2, 0) }, (_, i) => [`x${i + 2}`, `x${i + 1}`]));
  } else {
    regs = Array.from({ length: N - 1 }, (_, i) => `p${i + 1}`);
    if (regs.length) lines.push(decl(W, regs), decl(W, regs.map((_, i) => `pn${i + 1}`)));
    lines.push(decl(W, ['acc']));
    lines.push(`  assign acc = (${lit(h[0])}) * in_data` + (N > 1 ? ' + p1;' : ';'));
    for (let k = 1; k < N; k++) lines.push(`  assign pn${k} = (${lit(h[k])}) * in_data` + (k + 1 < N ? ` + p${k + 1};` : ';'));
    updates = regs.map((r, i) => [r, `pn${i + 1}`]);
  }
  roundAndLimit(lines, '', W, sh, sigFmt, overflow, 'y');
  return regsBlock(lines, regs.concat(['out_data']), updates.concat([['out_data', 'y']]));
}

function genSosSv(sosInt, coefFmt, sigFmt, { overflow = 'saturate', headroomBits = 0, errorFeedback = false, moduleName = 'sos_q' } = {}) {
  check(overflow, moduleName);
  const rows = sosInt.map(r => Array.from(r, Number)), SW = sigFmt.word, sh = coefFmt.fracBits, h = headroomBits, RW = Math.max(sh + 1, 2);
  const widths = rows.map(r => accWidthSos(r, coefFmt, sigFmt, errorFeedback));
  const extra = [`// Sections: ${rows.length} direct-form-I biquads. Section k accumulator: |acc + 2^(SH-1)| <= (|b0|+|b1|+|b2|+|a1|+|a2|) * 2^(SW-1)`,
    `//   + (|c1|+|c2|) * 2^(SH-1) + 2^(SH-1), so ACC_W per section = ${widths.join(', ')} bits.`,
    `// Input headroom: ${h} bit(s), applied as (in_data + 2^(h-1)) >>> h. The leftover gain is not in this module:`,
    `// multiply out_data by quantize_sos's gain times 2^${h} downstream.`];
  if (errorFeedback) extra.push(`// Error feedback: acc' = acc - c1*r[n-1] - c2*r[n-2], c = round(a); r = acc' - (yr <<< SH) is ${RW} bits.`);
  const lines = header(`${moduleName}: biquad cascade`, sigFmt, coefFmt, overflow, extra).concat(ports(moduleName, SW));
  let v;
  if (h > 0) { lines.push(decl(SW + 1, ['xh']), decl(SW, ['xs']), `  assign xh = in_data + ${lit(Math.pow(2, h - 1))};`, `  assign xs = xh >>> ${h};`); v = 'xs'; }
  else v = 'in_data';
  const regs = [], updates = [];
  rows.forEach((r, i) => {
    const p = `s${i}_`, [b0, b1, b2, a1, a2] = r, W = widths[i], st = [`${p}x1`, `${p}x2`, `${p}y1`, `${p}y2`];
    lines.push(`  // section ${i}: b = ${b0} ${b1} ${b2}, a = 1 ${a1} ${a2}`, decl(SW, st));
    let terms = `(${lit(b0)}) * ${v} + (${lit(b1)}) * ${p}x1 + (${lit(b2)}) * ${p}x2 - (${lit(a1)}) * ${p}y1 - (${lit(a2)}) * ${p}y2`;
    if (errorFeedback) {
      const [c1, c2] = efCoefs(r, sh);
      lines.push(decl(RW, [`${p}r1`, `${p}r2`, `${p}r`]));
      terms += `\n    - (${lit(c1)}) * ${p}r1 - (${lit(c2)}) * ${p}r2`;
      st.push(`${p}r1`, `${p}r2`);
    }
    lines.push(decl(W, [`${p}acc`]), `  assign ${p}acc = ${terms};`);
    roundAndLimit(lines, p, W, sh, sigFmt, overflow, `${p}y`);
    updates.push([`${p}x1`, v], [`${p}x2`, `${p}x1`], [`${p}y1`, `${p}y`], [`${p}y2`, `${p}y1`]);
    if (errorFeedback) { lines.push(`  assign ${p}r = ${p}acc - (${p}yr <<< ${sh});`); updates.push([`${p}r1`, `${p}r`], [`${p}r2`, `${p}r1`]); }
    regs.push(...st); v = `${p}y`;
  });
  return regsBlock(lines, regs.concat(['out_data']), updates.concat([['out_data', v]]));
}

function vectorsHex(xInt, yInt, sigFmt) {
  const SW = sigFmt.word, mask = (1n << BigInt(SW)) - 1n, digits = Math.floor((2 * SW + 3) / 4);
  let s = ''; for (let i = 0; i < xInt.length; i++) s += (((BigInt(xInt[i]) & mask) << BigInt(SW)) | (BigInt(yInt[i]) & mask)).toString(16).padStart(digits, '0') + '\n';
  return s;
}
function genTestbenchSv(moduleName, sigFmt, nVectors, vectorsFile) {
  const SW = sigFmt.word;
  return ['`timescale 1ns/1ps',
    `// Testbench for ${moduleName}, generated by Filterlab. Expected outputs come from simulate_*_fixed.`,
    `module ${moduleName}_tb;`,
    "  logic clk = 1'b0, rst = 1'b1, in_valid = 1'b0, out_valid;",
    `  logic signed [${SW - 1}:0] in_data = '0, out_data;`,
    `  logic [${2 * SW - 1}:0] vec [0:${nVectors - 1}];`,
    '  integer i, errors = 0;',
    `  ${moduleName} dut (.clk(clk), .rst(rst), .in_valid(in_valid), .in_data(in_data), .out_valid(out_valid), .out_data(out_data));`,
    '  always #5 clk = ~clk;',
    '  initial begin',
    `    $readmemh("${vectorsFile}", vec);`,
    '    repeat (2) @(posedge clk);',
    "    @(negedge clk) rst = 1'b0;",
    `    for (i = 0; i < ${nVectors}; i = i + 1) begin`,
    `      @(negedge clk) begin in_valid = 1'b1; in_data = vec[i][${2 * SW - 1}:${SW}]; end`,
    '      @(posedge clk) #1;',
    `      if (!out_valid || out_data !== $signed(vec[i][${SW - 1}:0])) begin`,
    '        errors = errors + 1;',
    `        if (errors <= 10) $display("mismatch at %0d: in %0d, got %0d, expected %0d", i, in_data, out_data, $signed(vec[i][${SW - 1}:0]));`,
    '      end',
    '    end',
    `    $display("${moduleName}: %0d vectors, %0d mismatches", ${nVectors}, errors);`,
    '    if (errors == 0) $display("PASS"); else $display("FAIL");',
    '    $finish;',
    '  end',
    'endmodule', ''].join('\n');
}

root.RTL = { genFirSv, genSosSv, genTestbenchSv, vectorsHex, accWidthFir, accWidthSos };
if (typeof module !== 'undefined') module.exports = root.RTL;
})(typeof window !== 'undefined' ? window : globalThis);
